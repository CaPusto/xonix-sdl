#!/usr/bin/env python3
"""Generate the bitmap font header used by the game.

Oxanium is a square, futuristic HUD typeface with strict outlines. The Bold
instance of the variable font is rasterised into a monochrome alpha atlas and
embedded directly in the binary, so the game needs neither SDL3_ttf nor an
installed system font. Oxanium is licensed under SIL OFL 1.1; the licence lives
in assets/fonts/Oxanium-OFL.txt.

The generated header is committed, so building the game needs neither Python
nor Pillow. Run this script only when changing the font or its metrics.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FIRST_CHAR = 32
LAST_CHAR = 126
GLYPH_COUNT = LAST_CHAR - FIRST_CHAR + 1

TTF = ROOT / "assets" / "fonts" / "Oxanium-Variable.ttf"
OUT = ROOT / "src" / "font_ui.h"
SIZE = 22
GLYPH_W = 22
GLYPH_H = 22
PREFIX = "FONT_UI"
ARRAY = "font_ui_alpha"


def build_atlas():
    font = ImageFont.truetype(str(TTF), SIZE)
    font.set_variation_by_name("Bold")
    atlas = Image.new("L", (GLYPH_W * GLYPH_COUNT, GLYPH_H), 0)
    draw = ImageDraw.Draw(atlas)

    for index, code in enumerate(range(FIRST_CHAR, LAST_CHAR + 1)):
        char = chr(code)
        offset = round((GLYPH_W - font.getlength(char)) / 2)
        draw.text((index * GLYPH_W + offset, 0), char, font=font,
                  fill=255, anchor="lt")
    return list(atlas.getdata())


def write_header(pixels):
    lines = [
        "/* Generated from Oxanium-Variable.ttf (Bold instance).",
        " * Oxanium is (c) 2019 The Oxanium Project Authors, SIL OFL 1.1.",
        " * Generated by tools/generate_font.py. Do not edit by hand. */",
        f"#ifndef XONIX_{PREFIX}_H",
        f"#define XONIX_{PREFIX}_H",
        "",
        f"#define {PREFIX}_FIRST       {FIRST_CHAR}",
        f"#define {PREFIX}_GLYPH_W     {GLYPH_W}",
        f"#define {PREFIX}_GLYPH_H     {GLYPH_H}",
        f"#define {PREFIX}_GLYPH_COUNT {GLYPH_COUNT}",
        "",
        f"static const unsigned char {ARRAY}[",
        f"    {PREFIX}_GLYPH_COUNT * {PREFIX}_GLYPH_W * {PREFIX}_GLYPH_H] = {{",
    ]
    for start in range(0, len(pixels), 16):
        lines.append("    " + ", ".join(str(v) for v in pixels[start:start + 16]) + ",")
    lines.extend(["};", "", f"#endif /* XONIX_{PREFIX}_H */", ""])
    OUT.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(pixels)} alpha bytes)")


def main() -> None:
    write_header(build_atlas())


if __name__ == "__main__":
    main()

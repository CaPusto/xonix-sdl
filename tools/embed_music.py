#!/usr/bin/env python3
"""Embed the OGG files into the executable as raw byte arrays.

The generated files are checked in, so a normal build needs no Python.  Run
this script again after replacing either file in music/:

    python3 tools/embed_music.py

Outputs (in src/):
    music_data.h   sizes and declarations
    music_data.c   raw OGG bytes in .rodata (no base64, no temp files)
"""

from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MUSIC = ROOT / "music"
OUT = ROOT / "src"

TRACKS = (
    ("main_theme_game.ogg", "XONIX_MUSIC_MAIN", "main game theme"),
    ("xonix_hiscore.ogg", "XONIX_MUSIC_HISCORE", "highscore theme"),
)

BYTES_PER_LINE = 24


def main() -> None:
    header = [
        "/* Generated by tools/embed_music.py - do not edit. */",
        "#ifndef XONIX_MUSIC_DATA_H",
        "#define XONIX_MUSIC_DATA_H",
        "",
        "/* Raw Ogg Vorbis files in .rodata. Decoded in RAM by music.c. */",
    ]
    source = [
        "/* Generated by tools/embed_music.py - do not edit. */",
        '#include "music_data.h"',
        "",
    ]

    for filename, symbol, description in TRACKS:
        data = (MUSIC / filename).read_bytes()
        size_symbol = f"{symbol}_SIZE"

        header.append(f"#define {size_symbol} {len(data)}u")
        header.append(f"extern const unsigned char {symbol}[{size_symbol}];"
                      f"  /* {description} */")
        source.append(f"const unsigned char {symbol}[{size_symbol}] = {{")
        for offset in range(0, len(data), BYTES_PER_LINE):
            chunk = data[offset:offset + BYTES_PER_LINE]
            line = "    " + ", ".join(str(byte) for byte in chunk)
            if offset + BYTES_PER_LINE < len(data):
                line += ","
            source.append(line)
        source.append("};")
        source.append("")

        print(f"{filename}: {len(data)} bytes embedded as raw data")

    header += ["", "#endif /* XONIX_MUSIC_DATA_H */", ""]

    (OUT / "music_data.h").write_text("\n".join(header))
    (OUT / "music_data.c").write_text("\n".join(source))
    print(f"wrote {OUT / 'music_data.h'} and {OUT / 'music_data.c'}")


if __name__ == "__main__":
    main()
